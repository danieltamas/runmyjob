import Foundation

/// The runner services a destination needs, derived from its runner targets in rules.json. The bundled compose file
/// holds only the shared settings; a target it has no service for gets a generated one in `docker-compose.rmj.yml`. Adding a runner is a rules.json edit, not a rebuild.
public struct RunnerCompose: Sendable, Equatable {
    public static let fileName = "docker-compose.rmj.yml"

    /// Every service to start, in target order.
    public let services: [String]
    /// The generated compose file, or nil when the bundled one already serves every target.
    public let generated: String?
    /// Runner services of the bundled file this destination does not use; they are stopped, never started.
    public let unused: [String]
    /// What a deploy must find on the destination to be current: the services and the generated file.
    public var manifest: String { services.joined(separator: "\n") + "\n" }

    public init(base: String, targets: [String], host: String) {
        let bundled = Self.bundledServices(base)
        var taken = Set(bundled.values)
        var names: [String] = []
        var blocks: [String] = []
        let version = Self.imageVersion(base)
        // A target or host that is not plain name characters never reaches the generated YAML.
        let host = String(host.map { $0.isASCII && ($0.isLetter || $0.isNumber || "-_.".contains($0)) ? $0 : "-" })
        for target in targets where RunnerTarget.path(target) != nil {
            if let service = bundled[Self.key(target)] { names.append(service); continue }
            let service = Self.serviceName(target, taken: taken)
            taken.insert(service)
            names.append(service)
            blocks.append(Self.block(service: service, target: target, host: host, version: version))
        }
        services = names
        unused = targets.isEmpty ? [] : Set(bundled.values).subtracting(names).sorted()
        generated = blocks.isEmpty ? nil : "# Generated by RMJ from the destination's runner targets. Do not edit.\nservices:\n" + blocks.joined(separator: "\n")
    }

    static func key(_ target: String) -> String { target.lowercased() }

    /// `target (lowercased, org: prefixed for an org) -> service` for the runner services of the bundled file.
    static func bundledServices(_ compose: String) -> [String: String] {
        var map = [String: String]()
        var service: String?
        var isOrg = false
        for line in compose.split(separator: "\n", omittingEmptySubsequences: false) {
            if line.hasPrefix("  runner-"), line.hasSuffix(":"), !line.hasPrefix("   ") {
                service = String(line.dropFirst(2).dropLast())
                isOrg = false
            } else if service != nil, let value = Self.value(of: "RUNNER_SCOPE", in: line) {
                isOrg = value == "org"
            } else if let name = service, let value = Self.value(of: "RUNNER_TARGET", in: line) {
                map[(isOrg ? "org:" : "") + value.lowercased()] = name
            }
        }
        return map
    }

    private static func value(of key: String, in line: Substring) -> String? {
        let trimmed = line.trimmingCharacters(in: .whitespaces)
        guard trimmed.hasPrefix(key + ":") else { return nil }
        return trimmed.dropFirst(key.count + 1).trimmingCharacters(in: .whitespaces)
    }

    static func imageVersion(_ compose: String) -> String {
        for line in compose.split(separator: "\n") {
            if let image = value(of: "image", in: line), image.hasPrefix("gh-runner:") { return String(image.dropFirst("gh-runner:".count)) }
        }
        return "latest"
    }

    /// `runner-<repo>` or `runner-<org>`; a name already taken falls back to `runner-<owner>-<repo>`.
    static func serviceName(_ target: String, taken: Set<String>) -> String {
        func slug(_ text: String) -> String {
            String(text.lowercased().map { $0.isASCII && ($0.isLetter || $0.isNumber) ? $0 : "-" })
        }
        let parts = target.hasPrefix("org:") ? [String(target.dropFirst(4))] : target.split(separator: "/").map(String.init)
        let short = "runner-" + slug(parts.last ?? target)
        if !taken.contains(short) { return short }
        let long = "runner-" + parts.map(slug).joined(separator: "-")
        var candidate = long
        var counter = 2
        while taken.contains(candidate) { candidate = "\(long)-\(counter)"; counter += 1 }
        return candidate
    }

    private static func block(service: String, target: String, host: String, version: String) -> String {
        let scope = target.hasPrefix("org:") ? "org" : "repo"
        let name = target.hasPrefix("org:") ? String(target.dropFirst(4)) : target
        let variable = RunnerTarget.environmentName(target) ?? "GH_PAT"
        let label = String(service.dropFirst("runner-".count))
        return """
          \(service):
            build: .
            image: gh-runner:\(version)
            container_name: \(service)
            restart: unless-stopped
            security_opt:
              - no-new-privileges:true
            pids_limit: 2048
            cpus: 4
            mem_limit: 8g
            networks: [ci]
            environment:
              RUNNER_LABELS_BASE: self-hosted,linux,x64,\(host)
              RUNNER_SCOPE: \(scope)
              RUNNER_TARGET: \(name)
              RUNNER_LABELS: \(label)
              GH_PAT: ${\(variable):?run through rmj}

        """
    }
}
