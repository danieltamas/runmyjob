#!/usr/bin/env bash
# Embeds Support/box (the box script) in Sources/RMJCore/Run/BoxAssets.swift,
# so the installed CLI carries them without a resource bundle. scripts/check.sh fails when this is stale.
set -euo pipefail
cd "$(dirname "$0")/.."
out=Sources/RMJCore/Run/BoxAssets.swift
mkdir -p "$(dirname "$out")"
{
  echo "// Generated by scripts/gen-box-assets.sh from Support/box. Do not edit."
  echo "enum BoxAssets {"
  echo '    static let script = #"""'
  cat Support/box/rx-run.sh
  echo '"""#'
  echo "}"
} > "$out"
